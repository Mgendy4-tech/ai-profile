/* eslint-disable @typescript-eslint/no-require-imports */
const { createHash } = require("node:crypto");
const { readFileSync } = require("node:fs");
const { resolve } = require("node:path");
const { chromium } = require("playwright-core");

const assert = (condition, message) => { if (!condition) throw new Error(message); };

(async () => {
  const browser = await chromium.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: true });
  const context = await browser.newContext({ acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(20000);
  const decisions = [];
  let generatedResponse = null;
  page.on("console", (message) => {
    if (message.text().includes("[authored-export-decision]")) decisions.push(message.text());
  });
  page.on("response", async (response) => {
    if (response.url().endsWith("/api/generate-profile") && response.ok()) generatedResponse = await response.json();
  });
  await page.goto("http://localhost:3000/company");
  console.log("browser: company page loaded");
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.locator('form input[type="text"]').nth(0).fill("Northbridge Advisory");
  await page.locator("form textarea").nth(0).fill("Northbridge Advisory is a business consulting firm that helps growing companies improve operations, clarify strategic priorities, and build more effective management processes. The firm works closely with leadership teams to identify operational challenges, structure practical solutions, and support sustainable business growth.");
  await page.locator('form input[type="text"]').nth(1).fill("Business Consulting & Advisory Services");
  await page.getByRole("button", { name: "Save Company" }).click();
  await page.waitForURL("**/generate", { timeout: 15000 });
  console.log("browser: company persisted and generate page loaded");
  await page.getByRole("button", { name: "Analyze Saved Company" }).click();
  await page.getByText(/tailored your profile structure/).waitFor({ timeout: 180000 });
  console.log("browser: structure analyzed");
  const analyzed = await page.evaluate(() => JSON.parse(localStorage.getItem("profileStructure")));
  assert(analyzed?.selectedSections?.length > 0, "Analyzed structure was not persisted.");
  const serviceSection = analyzed.selectedSections.find((section) => ["services", "mainActivities", "activities", "capabilities"].includes(section.id));
  assert(serviceSection, "Browser-analyzed Northbridge structure lacks a supported service section.");
  const serviceCard = page.locator("div.rounded-lg.border.border-gray-200.bg-white.p-4").filter({ hasText: serviceSection.displayTitle }).first();
  await serviceCard.getByRole("button", { name: new RegExp(`^Edit ${serviceSection.displayTitle}$`) }).click();
  await page.getByLabel(`${serviceSection.displayTitle} description`).fill(`${serviceSection.description} Preserve the approved service items below.`);
  const promptValues = ["Operations Advisory", "improve operations", "Strategic Priorities", "clarify strategic priorities"];
  page.on("dialog", async (dialog) => dialog.accept(promptValues.shift() ?? ""));
  await page.getByRole("button", { name: `Add item to ${serviceSection.displayTitle}` }).click();
  await page.getByRole("button", { name: `Add item to ${serviceSection.displayTitle}` }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  console.log("browser: service description and structured items edited");
  await page.getByRole("button", { name: /This Looks Good|Structure Confirmed/ }).click();
  await page.getByRole("button", { name: "Generate Profile" }).click();
  await page.getByRole("button", { name: "Download PDF" }).waitFor({ timeout: 180000 });
  console.log("browser: profile generated");
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem("profileStructure")));
  const selectedIds = persisted.selectedSections.map((section) => section.id);
  const persistedService = persisted.selectedSections.find((section) => section.id === serviceSection.id);
  assert(persistedService.items.length === 2 && persistedService.items.every((item) => item.id.startsWith(`${serviceSection.id}:service:`)), "Edited service items were not persisted with stable IDs.");
  assert(generatedResponse?.sections?.map((section) => section.id).join("|") === selectedIds.join("|"), "Generated response did not preserve every approved browser section.");
  const generatedService = generatedResponse.sections.find((section) => section.id === serviceSection.id);
  assert(generatedService.items.map((item) => item.id).join("|") === persistedService.items.map((item) => item.id).join("|"), "Generated services did not preserve approved stable item IDs and order.");
  const firstDownloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF" }).click();
  const firstDownload = await firstDownloadPromise;
  console.log("browser: first export downloaded");
  const outputPath = resolve("artifacts/manual-review/corporate-services-v1-northbridge-final-beta-review.pdf");
  await firstDownload.saveAs(outputPath);
  const secondDownloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF" }).click();
  const secondDownload = await secondDownloadPromise;
  console.log("browser: second export downloaded");
  const secondPath = await secondDownload.path();
  const firstBytes = readFileSync(outputPath); const secondBytes = readFileSync(secondPath);
  assert(firstBytes.equals(secondBytes), "Two browser exports from identical state must be byte-identical.");
  const raw = firstBytes.toString("latin1");
  assert(raw.includes("CORPORATE / SERVICES"), "Downloaded PDF lacks the Corporate authored marker.");
  assert(!/pexels|image credits/i.test(raw), "Downloaded PDF contains a legacy visual marker.");
  assert(decisions.some((entry) => entry.includes("authored") && entry.includes("corporate-services-v1")), "Browser export did not report Corporate authored success.");
  const pageText = await page.locator("body").innerText();
  assert(!pageText.includes("legacy"), "Browser flow exposed legacy fallback text.");
  await page.goto("http://localhost:3000/company");
  await page.evaluate(() => {
    const company = JSON.parse(localStorage.getItem("companyData")); company.logoUrl = "data:image/png;base64,OLD"; localStorage.setItem("companyData", JSON.stringify(company));
    localStorage.setItem("projectsData", JSON.stringify([{ id: "old-project", name: "Old Project", description: "Old", imageUrl: "data:image/png;base64,OLD" }]));
    localStorage.setItem("generatedProfile", JSON.stringify({ companyName: "Northbridge Advisory" }));
  });
  await page.reload();
  await page.locator('form input[type="text"]').nth(0).fill("Isolated Company Test");
  await page.getByRole("button", { name: "Save Company" }).click();
  await page.waitForURL("**/generate", { timeout: 15000 });
  const isolatedState = await page.evaluate(() => ({ company: JSON.parse(localStorage.getItem("companyData")), projects: JSON.parse(localStorage.getItem("projectsData")), structure: localStorage.getItem("profileStructure"), generated: localStorage.getItem("generatedProfile") }));
  assert(isolatedState.company.logoUrl === "" && isolatedState.projects.length === 0 && isolatedState.structure === null && isolatedState.generated === null, "Browser company switch leaked logo, projects, profile, or structure state.");
  console.log(JSON.stringify({ selectedIds, persistedSelectedIds: persisted.selectedSections.map((section) => section.id), persistedServiceItems: persistedService.items, generatedServiceItems: generatedService.items.map((item) => ({ id: item.id, name: item.name })), decisions, stateIsolation: { oldLogoCleared: true, oldProjectsCleared: true, oldProfileCleared: true, oldStructureCleared: true }, outputPath, bytes: firstBytes.length, sha256: createHash("sha256").update(firstBytes).digest("hex"), byteIdentical: true }, null, 2));
  await browser.close();
})().catch((error) => { console.error(error); process.exitCode = 1; });
